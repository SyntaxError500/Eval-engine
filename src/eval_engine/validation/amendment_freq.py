"""How often amendment fires, and how often it is accepted, per task type (plan Phase 9, design
§15: the ceiling-frequency question). From the accumulated traces, three sources:

1. Would amendment fire? Every experiment evaluation in the real store on a reviewed-bank
   question, one row per distinct judge request (reruns of the same answer share a cached
   reply). Recomputed uniformly from the trace, because older traces predate the
   `amendment_due` field: the shape allows other paths (analytical, explanatory), the answer
   addresses the question, and the top path confidence is under the threshold. Split by judge
   prompt (name and version), since score_answer v2 changed what the confidence means.
2. Phase 5 calibration: the same trigger on the verifier test set's answers, by kind.
3. Phase 5 end to end: what happened once amendment fired.

App submissions are left out (they are not experiments), and so is anything after CUTOFF, so
the report stays reproducible as the store grows. These are test answers written to probe the
engine, not a sample of real learners: the rates bound the machinery, they don't predict use.
"""

import json
import sqlite3
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

from eval_engine.config import REPO_ROOT
from eval_engine.evaluation.aggregate import load_bands
from eval_engine.schemas.common import SHAPE_FOR_TASK, SINGLE_PATH_SHAPES, TaskType

OUT_DIR = REPO_ROOT / "experiments" / "9_hardening"
BANK_FILE = REPO_ROOT / "experiments" / "3_generation" / "accepted.json"
VERIFIER_DIR = REPO_ROOT / "experiments" / "5_verifier"
CUTOFF = "2026-11-08T00:00:00"
TASK_ORDER = ["factual", "explanatory", "analytical", "creative"]


def _due(trace: dict[str, Any], threshold: float) -> bool:
    if SHAPE_FOR_TASK[TaskType(trace["task_type"])] in SINGLE_PATH_SHAPES:
        return False
    confs = [p["confidence"] for p in trace.get("path_confidences", [])]
    return trace.get("addresses_question") is True and bool(confs) and max(confs) < threshold


def store_rows(conn: sqlite3.Connection) -> list[dict[str, Any]]:
    bank = {e["question_id"] for e in json.loads(BANK_FILE.read_text(encoding="utf-8"))}
    app = {r[0] for r in conn.execute("SELECT evaluation_id FROM submissions")}
    calls = {
        r[0]: (r[1], f"{r[2]} v{r[3]}")
        for r in conn.execute(
            "SELECT call_id, request_key, prompt_name, prompt_version FROM llm_calls "
            "WHERE role = 'judge'"
        )
    }
    seen: set[str] = set()
    rows = []
    for eid, qid, body, _created in conn.execute(
        "SELECT evaluation_id, question_id, trace, created_at FROM evaluations "
        "WHERE created_at < ? ORDER BY created_at, evaluation_id",
        (CUTOFF,),
    ):
        if eid in app or qid not in bank:
            continue
        trace = json.loads(body)
        first = calls.get(trace["call_ids"][0]) if trace.get("call_ids") else None
        if first is None or first[0] in seen:
            continue
        seen.add(first[0])
        rows.append({"trace": trace, "judge_prompt": first[1]})
    return rows


def report(conn: sqlite3.Connection, verifier_dir: Path = VERIFIER_DIR) -> str:
    threshold = load_bands().amendment_confidence_threshold
    rows = store_rows(conn)
    table: dict[tuple[str, str], list[int]] = defaultdict(lambda: [0, 0])
    for r in rows:
        cell = table[(r["trace"]["task_type"], r["judge_prompt"])]
        cell[0] += 1
        cell[1] += _due(r["trace"], threshold)
    versions = sorted({v for _, v in table})
    lines = [
        "# How often amendment fires (plan Phase 9, design §15)",
        "",
        "Generated by `eval-engine amendment-frequency`; method in "
        "`src/eval_engine/validation/amendment_freq.py`. Test answers written to probe the "
        "engine, not real learners: these rates bound the machinery, they don't predict use.",
        "",
        f"## 1. Would amendment fire? (reviewed-bank questions, threshold {threshold})",
        "",
        "One row per distinct judge request, so reruns of the same answer count once. "
        "Factual and creative rubrics have one path by design, so amendment never applies.",
        "",
        "| Task type | " + " | ".join(f"`{v}`" for v in versions) + " |",
        "|---|" + "---|" * len(versions),
    ]
    for task in TASK_ORDER:
        cells = []
        for v in versions:
            n, due = table.get((task, v), [0, 0])
            cells.append(f"{due}/{n} ({due / n:.0%})" if n else "-")
        lines.append(f"| {task} | " + " | ".join(cells) + " |")

    calibration = json.loads((verifier_dir / "calibration.json").read_text(encoding="utf-8"))
    by_kind: dict[str, list[int]] = defaultdict(lambda: [0, 0])
    for c in calibration:
        by_kind[c["kind"]][0] += 1
        by_kind[c["kind"]][1] += c["addresses"] is True and c["confidence"] < threshold
    lines += [
        "",
        "## 2. Phase 5 verifier test set: does the trigger fire?",
        "",
        "Analytical and explanatory questions only. `valid_unlisted` answers take a sound route "
        "the rubric lacks (amendment should fire); the other kinds are wrong (it may fire, and "
        "the proposer or verifier must then refuse).",
        "",
        "| Answer kind | Fires |",
        "|---|---|",
    ]
    for kind, (n, due) in sorted(by_kind.items()):
        lines.append(f"| {kind} | {due}/{n} ({due / n:.0%}) |")

    e2e = json.loads((verifier_dir / "e2e.json").read_text(encoding="utf-8"))
    outcomes = Counter((r["kind"], r["outcome"]) for r in e2e)
    lines += [
        "",
        "## 3. Phase 5 end to end: once it fires, what happens",
        "",
        "| Answer kind | Outcome | n |",
        "|---|---|---|",
    ]
    for (kind, outcome), n in sorted(outcomes.items()):
        lines.append(f"| {kind} | {outcome} | {n} |")
    accepted = sum(n for (_, o), n in outcomes.items() if o == "accepted")
    valid = sum(n for (k, _), n in outcomes.items() if k == "valid_unlisted")
    wrong_accepted = sum(
        n for (k, o), n in outcomes.items() if o == "accepted" and k != "valid_unlisted"
    )
    lines += [
        "",
        f"Accepted: {accepted} of {len(e2e)} that fired. Every valid unlisted route that fired "
        f"was accepted ({valid}); wrong answers accepted: {wrong_accepted} (Phase 5 "
        "findings discuss the `holed` case).",
    ]
    return "\n".join(lines) + "\n"
